#!/usr/bin/env python3
"""Build papers.yml from arXiv-verified metadata plus an explicit structure.

Metadata (title / authors / year / abs URL) comes from `verified-metadata.json`, which is
produced by `verify_papers.py` querying the arXiv API. Nothing in this file is hand-typed, and
the script refuses to run if any paper it references is missing from that file.

This script decides only grouping: which paper is a top-level entry, what its topics are, and
which papers are listed as its related items.

Author field follows software-papers' convention: first author's surname, plus " et al" when
there are more than two authors, or "A, B" for exactly two.
"""
import json
import re
from pathlib import Path

HERE = Path(__file__).parent
BY_ID = {r["id"]: r for r in json.loads((HERE / "verified-metadata.json").read_text())}

# top-level paper -> its topics and the related papers listed beneath it
STRUCTURE = [
    ("2201.11903", ["Reasoning", "Prompting"],
     ["2203.11171", "2205.10625", "2305.10601"]),
    ("2210.03629", ["Agents", "Reasoning and Acting"],
     ["2303.11366", "2303.17651", "2305.20050", "2406.02818"]),
    ("2302.04761", ["Tool Use", "Function Calling"],
     ["2307.16789", "2305.15334", "2402.01030"]),
    ("2310.08560", ["Agent Memory", "Long-Term Memory"],
     ["2304.03442", "2502.12110", "2504.19413", "2410.10813"]),
    ("2005.11401", ["Retrieval", "Knowledge Grounding"],
     ["2310.11511", "2307.03172"]),
    ("2309.02427", ["Agent Architecture", "Survey"],
     ["2309.07864", "2308.11432", "2504.16736"]),
    ("2310.06770", ["Coding Agents", "Benchmarks"],
     ["2405.15793", "2407.16741"]),
    ("2307.13854", ["Web Agents", "Environments"],
     ["2404.07972"]),
    ("2308.08155", ["Multi-Agent", "Orchestration"],
     ["2308.00352", "2303.17760", "2307.07924", "2503.13657"]),
    ("2407.01502", ["Evaluation", "Rigor"],
     ["2308.03688", "2406.12045", "2410.10934", "2506.06941"]),
    ("2203.02155", ["Alignment", "Training"],
     ["2305.18290", "2212.08073", "2501.12948"]),
    ("2408.03314", ["Test-Time Compute", "Scaling"],
     ["2503.14499", "2512.08296"]),
    ("2305.16291", ["Open-Ended Agents", "Lifelong Learning"],
     []),
]


def clean_title(t):
    """arXiv returns LaTeX in a few titles; normalise those that leak through."""
    t = t.replace("$\\tau$-bench", "τ-bench").replace("$\\tau$", "τ")
    return re.sub(r"\s+", " ", t).strip()


def yaml_scalar(s):
    """Quote a plain scalar when it contains YAML-significant text.

    Most agent paper titles contain ': ' (ReAct: ..., SWE-bench: ...), which turns an unquoted
    plain scalar into a mapping and breaks the parser. software-papers quotes those too.
    """
    if not (": " in s or s.endswith(":") or s[:1] in "-?:,[]{}#&*!|>'\"%@`"):
        return s
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def author_field(authors):
    if not authors:
        return "Unknown"
    surnames = [a.split()[-1] for a in authors]
    if len(surnames) == 1:
        return surnames[0]
    if len(surnames) == 2:
        return f"{surnames[0]}, {surnames[1]}"
    return f"{surnames[0]} et al"


def stable_link(rec):
    m = re.search(r"arxiv\.org/abs/([^v\s]+)", rec["link"])
    return f"https://arxiv.org/abs/{m.group(1)}" if m else rec["link"]


def entry(rec, indent):
    pad = " " * indent
    return [f"{pad}- title: {yaml_scalar(clean_title(rec['title']))}",
            f"{pad}  author: {yaml_scalar(author_field(rec['authors']))}",
            f"{pad}  year: {rec['year']}",
            f"{pad}  link: {stable_link(rec)}"]


def main():
    missing = sorted({i for top, _t, rel in STRUCTURE for i in (top, *rel)} - set(BY_ID))
    if missing:
        raise SystemExit(f"not verified, refusing to write: {missing}")

    lines = ["# Papers on LLM agents and agent systems.",
             "# Metadata is generated by build_papers.py from arXiv-verified data; do not hand-edit.",
             "# Regenerate with: python3 verify_papers.py && python3 build_papers.py "
             "&& python3 gen_readme.py > README.md"]
    seen = set()
    for top_id, topics, related_ids in STRUCTURE:
        lines += [""]
        lines += entry(BY_ID[top_id], 0)
        lines.append(f"  topics: [{', '.join(topics)}]")
        if related_ids:
            lines.append("  related:")
            for rid in sorted(related_ids, key=lambda r: BY_ID[r]["year"]):
                lines += entry(BY_ID[rid], 4)
        seen.add(top_id)
        seen.update(related_ids)

    (HERE / "papers.yml").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote papers.yml  ({len(seen)} papers: {len(STRUCTURE)} top-level "
          f"+ {len(seen) - len(STRUCTURE)} related)")
    if unused := sorted(set(BY_ID) - seen):
        print(f"verified but not placed: {unused}")


if __name__ == "__main__":
    main()
